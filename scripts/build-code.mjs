// Bundles the P&L engine (src/pl/code-entry.ts) into config/code/compute_pl.js, the compute_pl Code step's source.
// `pnpm build` runs this first; test/pl/code-bundle.test.ts fails when the committed file is behind the source.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const OUT = 'config/code/compute_pl.js';

// The Code runner calls main(inputs); it may read only the step's declared inputs, input and config.
const MAIN = 'function main(inputs) {\n  return PL.runComputePl({ input: inputs.input, config: inputs.config });\n}\n';

export async function bundle() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['src/pl/code-entry.ts'],
    bundle: true,
    format: 'iife',
    globalName: 'PL',
    target: 'es2020',
    minify: false,
    write: false,
    legalComments: 'none',
    banner: { js: '// GENERATED by scripts/build-code.mjs — do not edit' },
    logLevel: 'silent',
  });
  return `${result.outputFiles[0].text}${MAIN}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(`${root}${OUT}`, await bundle());
  console.log(`wrote ${OUT}`);
}
